def check_composite() -> list[str]:
    if len(COMPOSITE) != 64:
        raise SystemExit(f"composite palette has {len(COMPOSITE)} entries, not 64")
    out = []
    for index, (text, red, green, blue) in enumerate(COMPOSITE):
        if f"{red:02X}{green:02X}{blue:02X}" != text.upper():
            raise SystemExit(
                f"composite {index}: hex {text} and decimal "
                f"({red}, {green}, {blue}) disagree"
            )
        out.append(f"#{text.upper()}")
    return out


def rgb_palette() -> list[str]:
    """Index bits are R1 G1 B1 R0 G0 B0; each channel is (2*high + low) * 85."""
    out = []
    for index in range(64):
        channels = []
        for high, low in ((4, 32), (2, 16), (1, 8)):
            # low nibble carries R0/G0/B0 in bits 2/1/0, high in bits 5/4/3.
            channels.append((2 * bool(index & low) + bool(index & high)) * 85)
        out.append("#{:02X}{:02X}{:02X}".format(*channels))
    return out


# Semantic names for the deck. These are choices, not measurements: the
# MC6847 in a CoCo 1 makes about nine colours, and these are the entries in
# the CoCo 3 composite table that sit closest to them. Change them freely.
ROLES = {
    "bg": 18,  # the text screen's green, and the deck's page colour
    "ink": 0,  # black, and what the CoCo draws letters in
    "bar": 34,  # bright green for the reversed title bar's text
    "white": 63,  # the cursor block, and buff in graphics modes
    "grey": 32,  # for rules and de-emphasised text
    "win": 17,  # the win mark in the game opponent
    "tie": 28,  # the tie mark
    "loss": 22,  # the loss mark
    "amber": 36,  # highlight, and the closest thing to VDG yellow
    "orange": 21,
    "cyan": 46,
    "magenta": 25,
}


def main() -> None:
    composite = check_composite()
    rgb = rgb_palette()

    lines = [
        "/* CoCo colour palettes. Generated by tools/make_coco_palette.py.",
        "   Do not edit; change the generator. */",
        ":root {",
        "  /* Composite: what a Color Computer looks like on a television.",
        "     This is the deck's palette. */",
    ]
    lines += [f"  --coco-c{i:02d}: {c};" for i, c in enumerate(composite)]
    lines.append("")
    lines.append("  /* RGB: the sharper monitor palette, four levels per channel. */")
    lines += [f"  --coco-r{i:02d}: {c};" for i, c in enumerate(rgb)]
    lines.append("")
    lines.append("  /* Roles. Composite entries chosen for the deck. */")
    lines += [
        f"  --coco-{name}: var(--coco-c{index:02d}); /* {composite[index]} */"
        for name, index in ROLES.items()
    ]
    lines.append("}")
    OUT_CSS.write_text("\n".join(lines) + "\n", encoding="ascii")

    OUT_JSON.write_text(
        json.dumps(
            {
                "composite": composite,
                "rgb": rgb,
                "roles": {
                    n: {"index": i, "hex": composite[i]} for n, i in ROLES.items()
                },
            },
            indent=2,
        )
        + "\n",
        encoding="ascii",
    )
    print(
        f"64 composite, 64 rgb, {len(ROLES)} roles -> {OUT_CSS.name}, {OUT_JSON.name}"
    )


if __name__ == "__main__":
    main()
