"""Generate the CoCo colour palettes for the browser deck.

Two palettes, from the Color Computer 3's palette registers.

The RGB palette is derivable and is computed here rather than typed. Its index
bits are R1 G1 B1 R0 G0 B0, and each channel is (high * 2 + low) * 85, giving
four levels per channel and 64 colours.

The composite palette is not derivable. It is what the NTSC encoder actually
produces, so it has to be measured, and the values below were transcribed from
Stacey's palette reference. Transcription by eye is the weak step, so every
entry carries both the hex string and the decimal triple from that table and
the two have to agree. A slipped digit fails here rather than in the deck.

Composite is the one the deck uses. It is what a CoCo on a television looks
like, which is the point.
"""

